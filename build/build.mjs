/**
 * Nemo token build.
 * One source of truth (tokens/*.json, DTCG) → many platforms.
 *
 *   web/nemo.css        CSS custom properties (:root)  — light
 *   web/nemo.dark.css   CSS custom properties (.dark)  — dark overrides
 *   ts/tokens.ts        Flat TS consts (+ .d.ts)       — web
 *   rn/theme.ts         Nested { light, dark } theme   — React Native
 *   flutter/nemo_tokens.dart  Dart class                — Flutter
 *
 * Web themes via CSS vars; RN/Flutter can't use CSS vars, so they get
 * fully-resolved light & dark objects instead.
 */
import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const BUILD = resolve(ROOT, 'build');
const CORE = resolve(ROOT, 'tokens/core.json');
const SEM_LIGHT = resolve(ROOT, 'tokens/semantic.light.json');
const SEM_DARK = resolve(ROOT, 'tokens/semantic.dark.json');
// Hand-authored, NOT from Figma — see tokens/fixed.json's own $description.
const FIXED = resolve(ROOT, 'tokens/fixed.json');

const PREFIX = 'nemo';

/* ---------- helpers ---------- */

const hexToFlutter = (hex) => {
  let h = hex.replace('#', '').trim();
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  // DTCG hex-with-alpha is #RRGGBBAA; Dart wants 0xAARRGGBB.
  if (h.length === 8) {
    const r = h.slice(0, 2), g = h.slice(2, 4), b = h.slice(4, 6), a = h.slice(6, 8);
    h = a + r + g + b;
  } else if (h.length === 6) {
    h = 'ff' + h; // opaque
  }
  return `0x${h.toUpperCase()}`;
};

const px = (v) => parseFloat(String(v));

const dartName = (path) => {
  const camel = path
    .map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1)))
    .join('')
    .replace(/[^a-zA-Z0-9]/g, '');
  return camel.charAt(0).toLowerCase() + camel.slice(1);
};

// Build a nested object from flat tokens (resolved values), skipping the leading group.
const nest = (tokens) => {
  const out = {};
  for (const t of tokens) {
    let node = out;
    const path = t.path;
    for (let i = 0; i < path.length - 1; i++) {
      node[path[i]] ??= {};
      node = node[path[i]];
    }
    node[path[path.length - 1]] = t.value ?? t.$value;
  }
  return out;
};

/* ---------- custom formats ---------- */

StyleDictionary.registerFormat({
  name: 'nemo/dart',
  format: ({ dictionary }) => {
    const lines = [];
    lines.push('// GENERATED by Nemo token build — do not edit by hand.');
    lines.push("import 'package:flutter/widgets.dart';\n");
    lines.push('class NemoTokens {');
    lines.push('  NemoTokens._();\n');
    for (const t of dictionary.allTokens) {
      const name = dartName(t.path);
      const type = t.$type ?? t.type;
      const val = t.value ?? t.$value;
      if (type === 'color') {
        lines.push(`  static const Color ${name} = Color(${hexToFlutter(val)});`);
      } else if (type === 'dimension' || type === 'number' || type === 'fontWeight') {
        lines.push(`  static const double ${name} = ${px(val)};`);
      } else if (type === 'shadow') {
        const list = Array.isArray(val) ? val : [val];
        const boxes = list
          .map(
            (s) =>
              `BoxShadow(color: Color(${hexToFlutter(s.color)}), ` +
              `offset: Offset(${px(s.offsetX)}, ${px(s.offsetY)}), ` +
              `blurRadius: ${px(s.blur)}, spreadRadius: ${px(s.spread)})`
          )
          .join(', ');
        lines.push(`  static const List<BoxShadow> ${name} = [${boxes}];`);
      }
      // fontFamily / arrays skipped for Dart
    }
    lines.push('}');
    return lines.join('\n') + '\n';
  },
});

StyleDictionary.registerFormat({
  name: 'nemo/manifest',
  // Flat list of every token with its CSS var name — powers the Storybook viewers.
  format: ({ dictionary }) =>
    JSON.stringify(
      dictionary.allTokens.map((t) => ({
        name: `--${t.name}`,
        path: t.path,
        type: t.$type ?? t.type,
        value: t.value ?? t.$value,
      })),
      null,
      2
    ) + '\n',
});

StyleDictionary.registerFormat({
  name: 'nemo/rn-theme',
  // emits: export const light = {...} as const  (name comes from options.themeName)
  format: ({ dictionary, options }) => {
    const themeName = options.themeName ?? 'theme';
    const obj = nest(dictionary.allTokens);
    return (
      `// GENERATED by Nemo token build — do not edit by hand.\n` +
      `export const ${themeName} = ${JSON.stringify(obj, null, 2)} as const;\n`
    );
  },
});

/* ---------- filters ---------- */

StyleDictionary.registerFilter({
  name: 'nemo/isDarkSemantic',
  filter: (token) => token.filePath === SEM_DARK,
});

/* ---------- instances ---------- */

// LIGHT: core + light semantic + fixed pins → CSS :root, TS, Flutter, RN light theme
const light = new StyleDictionary({
  source: [CORE, SEM_LIGHT, FIXED],
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: PREFIX,
      buildPath: `${BUILD}/web/`,
      files: [
        {
          destination: 'nemo.css',
          format: 'css/variables',
          options: { selector: ':root', outputReferences: true },
        },
        { destination: '../manifest.json', format: 'nemo/manifest' },
      ],
    },
    ts: {
      transformGroup: 'js',
      prefix: PREFIX,
      buildPath: `${BUILD}/ts/`,
      files: [
        { destination: 'tokens.ts', format: 'javascript/es6' },
        { destination: 'tokens.d.ts', format: 'typescript/es6-declarations' },
      ],
    },
    flutter: {
      transforms: ['attribute/cti', 'color/hex'],
      buildPath: `${BUILD}/flutter/`,
      files: [{ destination: 'nemo_tokens.dart', format: 'nemo/dart' }],
    },
    rnLight: {
      transforms: ['attribute/cti', 'color/hex'],
      buildPath: `${BUILD}/rn/`,
      files: [
        {
          // Includes CORE + FIXED too (not just the semantic alias tree) so
          // RN can reference primitives and the "-fixed" pins (e.g.
          // `light.color.fixed.success`) the same way Flutter's NemoTokens
          // already can — no hardcoded hex needed for badge.tsx's solid variant.
          destination: 'theme.light.ts',
          format: 'nemo/rn-theme',
          filter: (t) => t.filePath === SEM_LIGHT || t.filePath === CORE || t.filePath === FIXED,
          options: { themeName: 'light' },
        },
      ],
    },
  },
});

// DARK: core + dark semantic + fixed pins → CSS .dark, RN dark theme
const dark = new StyleDictionary({
  source: [CORE, SEM_DARK, FIXED],
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: PREFIX,
      buildPath: `${BUILD}/web/`,
      files: [
        {
          destination: 'nemo.dark.css',
          format: 'css/variables',
          filter: 'nemo/isDarkSemantic',
          options: { selector: '.dark', outputReferences: true },
        },
      ],
    },
    rnDark: {
      transforms: ['attribute/cti', 'color/hex'],
      buildPath: `${BUILD}/rn/`,
      files: [
        {
          // Same primitive + fixed access as rnLight above — neither has a
          // dark variant, so this duplicates the same values, not a divergent set.
          destination: 'theme.dark.ts',
          format: 'nemo/rn-theme',
          filter: (t) => t.filePath === SEM_DARK || t.filePath === CORE || t.filePath === FIXED,
          options: { themeName: 'dark' },
        },
      ],
    },
  },
});

await light.buildAllPlatforms();
await dark.buildAllPlatforms();

console.log('\n🐟  Nemo tokens built → build/{web,ts,rn,flutter}');
